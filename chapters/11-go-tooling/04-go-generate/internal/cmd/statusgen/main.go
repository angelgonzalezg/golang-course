// Command statusgen generates status constants and a name table from a text file.
package main

import (
	"bufio"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"os"
	"strings"
)

func parseNames(input []byte) ([]string, error) {
	var names []string
	seen := make(map[string]bool)
	scanner := bufio.NewScanner(bytes.NewReader(input))
	lineNumber := 0
	for scanner.Scan() {
		lineNumber++
		name := strings.TrimSpace(scanner.Text())
		if name == "" || strings.HasPrefix(name, "#") {
			continue
		}
		if name == "_" || !token.IsIdentifier(name) {
			return nil, fmt.Errorf("line %d: invalid status name %q", lineNumber, name)
		}
		if seen[name] {
			return nil, fmt.Errorf("line %d: duplicate status name %q", lineNumber, name)
		}
		seen[name] = true
		names = append(names, name)
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("read status names: %w", err)
	}
	if len(names) == 0 {
		return nil, errors.New("at least one status name is required")
	}
	return names, nil
}

func render(input []byte) ([]byte, error) {
	names, err := parseNames(input)
	if err != nil {
		return nil, err
	}
	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by statusgen; DO NOT EDIT.")
	fmt.Fprintln(&output, "package main")
	fmt.Fprintln(&output, "const (")
	for index, name := range names {
		if index == 0 {
			fmt.Fprintf(&output, "Status%s Status = iota\n", name)
		} else {
			fmt.Fprintf(&output, "Status%s\n", name)
		}
	}
	fmt.Fprintln(&output, ")")
	fmt.Fprintln(&output, "var statusNames = [...]string{")
	for _, name := range names {
		fmt.Fprintf(&output, "%q,\n", name)
	}
	fmt.Fprintln(&output, "}")
	// The formatter also checks the syntax of the generated Go source.
	return format.Source(output.Bytes())
}

func generateFile(inputPath, outputPath string) error {
	input, err := os.ReadFile(inputPath)
	if err != nil {
		return fmt.Errorf("read input: %w", err)
	}
	generated, err := render(input)
	if err != nil {
		return fmt.Errorf("generate statuses: %w", err)
	}
	// Validate and format everything before opening the previous output for writing.
	// Invalid input therefore leaves that file untouched.
	if err := os.WriteFile(outputPath, generated, 0o644); err != nil {
		return fmt.Errorf("write generated source: %w", err)
	}
	return nil
}

func main() {
	input := flag.String("in", "statuses.txt", "input status names")
	output := flag.String("out", "status_names_gen.go", "generated Go source")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "statusgen accepts -in and -out flags, without positional arguments")
		os.Exit(2)
	}
	if err := generateFile(*input, *output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
